// Builds Neon Hub's Macros compendium (packs/_source/macros) and its icons (assets/macros), one macro per window,
// like Neon Combat Manager's and Neon At Home's. Run with `node tools/gen-macros.mjs`; ids come from the names, so
// re-running keeps them. Each macro calls Neon Hub's API, so it works from the hotbar, Neon Combat Manager's Action
// HUD (where its `actor` is the HUD's character), a hub button or an active tile.
import { createHash } from "node:crypto";
import { mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const MODULE_ID = "cpr-neon-hub";
const B62 = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
const rid = (s) => {
  let h = BigInt(`0x${createHash("sha1").update(`macro|${s}`).digest("hex")}`);
  let out = "";
  for (let i = 0; i < 16; i++) {
    out += B62[Number(h % 62n)];
    h /= 62n;
  }
  return out;
};

const WHO = 'const who = (typeof actor !== "undefined" && actor) || (typeof character !== "undefined" && character) || null;';
// key, name, what it opens, the call (`hub` is Neon Hub's API, `who` the macro's character), GM only, the glyph's paths
const MACROS = [
  ["lifestyle", "Lifestyle", "open Lifestyle (rent, bills and the month) for the selected token's character (or your own)", "hub.openLifestyle(who)", false,
    "M118 176h276v192H118zM118 214h276M310 266h52v48h-52z"],
  ["calendar", "Calendar", "open the crew's calendar", "hub.openCalendar()", false,
    "M120 150h272v236H120zM120 208h272M176 118v64M336 118v64M168 262h40M236 262h40M304 262h40M168 322h40M236 322h40"],
  ["cred", "Street Cred", "open Street Cred (Reputation, Standing and Heat) for the selected token's character (or your own)", "hub.cred.open(who)", false,
    "M256 116l38 80 88 12-64 62 16 88-78-42-78 42 16-88-64-62 88-12z"],
  ["fashion", "Style Check", "open Style Check for the selected token's character (or your own)", "hub.fashion.open(who)", false,
    "M196 130l-84 50 30 64 34-16v164h160V228l34 16 30-64-84-50c-8 30-30 46-60 46s-52-16-60-46z"],
  ["hq", "Headquarters", "open the crew's Headquarters (or pick one)", "hub.chooseHQ()", false,
    "M110 384h292M142 384V220l114-86 114 86v164M216 384v-86h80v86M186 250h40M286 250h40"],
  ["journal", "Neon Journal", "open the Neon Journal", "hub.journal.open()", false,
    "M256 168c-40-34-92-40-140-32v232c48-8 100-2 140 32 40-34 92-40 140-32V136c-48-8-100-2-140 32zM256 168v232"],
  ["downtime", "Downtime", "open the Downtime window (the crew's time to spend)", "hub.downtime.open()", false,
    "M256 126a130 130 0 1 0 0.1 0zM256 180v86l60 40"],
  ["skipTime", "Skip Time", "open Skip time on every connected screen (players vote, you wind the clock on)", "hub.skipTime()", true,
    "M134 150l110 106-110 106zM262 150l110 106-110 106z"],
  ["editHub", "New Hub Page", "open the hub editor for a new hub page", "hub.editHub()", true,
    "M120 130h120v120H120zM272 130h120v120H272zM120 282h120v120H120zM332 288v108M278 342h108"]
];

const icon = (key, glyph) => `<svg width="512" height="512" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <!-- Neon Hub macro icon: ${key}. Generated by tools/gen-macros.mjs. -->
  <path d="M24 24h420l44 44v420H68l-44-44z" fill="#07070b" stroke="#ff2a6d" stroke-width="16"/>
  <path d="M56 452h120" stroke="#f3e600" stroke-width="10"/>
  <g fill="none" stroke="#05d9e8" stroke-width="26" stroke-linecap="round" stroke-linejoin="round"><path d="${glyph}"/></g>
</svg>
`;

const command = (name, what, call, gm) =>
  [
    `// Neon Hub: ${what}.`,
    "// Works from the hotbar, Neon Combat Manager's Action HUD, a Neon Hub page button or an active tile.",
    `const hub = game.modules.get("${MODULE_ID}")?.api;`,
    `if (!hub) return ui.notifications.warn("Neon Hub isn't active in this world.");`,
    ...(gm ? [`if (!game.user.isGM) return ui.notifications.warn("${name} is for the GM.");`] : []),
    WHO,
    `return ${call};`,
    ""
  ].join("\n");

const packDir = path.join(root, "packs/_source/macros");
const iconDir = path.join(root, "assets/macros");
await rm(packDir, { recursive: true, force: true });
await mkdir(packDir, { recursive: true });
await mkdir(iconDir, { recursive: true });
let sort = 0;
for (const [key, name, what, call, gm, glyph] of MACROS) {
  const _id = rid(key);
  await writeFile(path.join(iconDir, `${key}.svg`), icon(key, glyph));
  const doc = {
    _id,
    _key: `!macros!${_id}`,
    name: `Neon Hub: ${name}`,
    type: "script",
    scope: "global",
    img: `modules/${MODULE_ID}/assets/macros/${key}.svg`,
    command: command(name, what, call, gm),
    folder: null,
    sort: (sort += 100),
    ownership: { default: 0 },
    flags: { [MODULE_ID]: { macro: key, gm } }
  };
  await writeFile(path.join(packDir, `${key}_${_id}.json`), `${JSON.stringify(doc, null, 2)}\n`);
}
console.log(`${MACROS.length} macros`);
